#ifndef B5Q_WIFI_FIRMWARE_NAME_H
#define B5Q_WIFI_FIRMWARE_NAME_H
#include <stdbool.h>
#include <stdint.h>
#if !defined(KERNEL)
#include <stdio.h>
#endif
#include <string.h>
// Samsung cnss2 qmi.c cnss_get_bdf_file_name. Never pick a calibration file
// from an unrelated board ID. Optional antenna suffixes are explicit inputs.
static inline bool b5q_wifi_bdf_name(char *out,size_t capacity,uint32_t chip,uint32_t board,unsigned antenna) {
    if(!out || capacity<24 || board>0xffff || (antenna && antenna!=1 && antenna!=2 && antenna!=10))return false;
    const char *prefix=(chip&0x10)?"bdwlang":"bdwlan";
    if(board==0xff)snprintf(out,capacity,"%s.elf",prefix);
    else if(board<0xff)snprintf(out,capacity,"%s.e%02x",prefix,board);
    else snprintf(out,capacity,"bdwlan%02x.e%02x",(board>>8)&255,board&255);
    if(antenna){size_t n=strlen(out);snprintf(out+n,capacity-n,"%u",antenna);}
    return true;
}
static inline bool b5q_wifi_firmware_name(const char *name) {
    if(!name || !*name || strlen(name)>64)return false;
    // Linux's firmware shim supplies the final path component. No absolute
    // path, subdirectory, Apple binary or arbitrary vendor file is allowed.
    for(const char *p=name;*p;p++)if(*p=='/' || *p=='\\')return false;
    if(!strcmp(name,"amss.bin") || !strcmp(name,"amss20.bin") || !strcmp(name,"m3.bin") || !strcmp(name,"regdb.bin"))return true;
    // Accept only names generated by cnss_get_bdf_file_name, including its
    // optional antenna suffix. A prefix match is not a firmware allowlist.
    char expected[64];
    const char *p=name;
    if(strncmp(p,"bdwlan",6))return false;
    p+=6;
    unsigned chip=0,board=0xff;
    if(*p=='g'){chip=0x10;p++;}
    unsigned high=0;
    if(*p!='.') {
        for(unsigned i=0;i<2;i++) {
            unsigned v=(*p>='0'&&*p<='9')?(unsigned)(*p-'0'):
                (*p>='a'&&*p<='f')?(unsigned)(*p-'a'+10):16;
            if(v>15)return false;high=(high<<4)|v;p++;
        }
        if(chip || !high)return false;
    }
    if(*p++!='.')return false;
    if(!strncmp(p,"elf",3)){if(high)return false;p+=3;}
    else {
        if(*p++!='e')return false;board=high<<8;
        for(unsigned i=0;i<2;i++) {
            unsigned v=(*p>='0'&&*p<='9')?(unsigned)(*p-'0'):
                (*p>='a'&&*p<='f')?(unsigned)(*p-'a'+10):16;
            if(v>15)return false;board|=v<<(4*(1-i));p++;
        }
    }
    unsigned antenna=0;
    if(!strcmp(p,"1"))antenna=1;else if(!strcmp(p,"2"))antenna=2;
    else if(!strcmp(p,"10"))antenna=10;else if(*p)return false;
    return b5q_wifi_bdf_name(expected,sizeof(expected),chip,board,antenna) && !strcmp(name,expected);
}
#endif
