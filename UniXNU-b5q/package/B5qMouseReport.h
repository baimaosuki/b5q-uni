// Report 1a: [ID, buttons(2)+padding(6), X s16le, Y s16le, wheel s8, pan s8].
// Usage pages: Generic Desktop(1), Button(9), Consumer(0c). Input 06 = relative.
static constexpr unsigned char mouseDescriptor[]={
    0x05,0x01,0x09,0x02,0xa1,0x01,0x85,0x1a,0x09,0x01,0xa1,0x00,
    0x05,0x09,0x19,0x01,0x29,0x02,0x15,0x00,0x25,0x01,
    0x75,0x01,0x95,0x02,0x81,0x02, // Buttons 1(left), 2(right)
    0x75,0x06,0x95,0x01,0x81,0x03, // byte alignment
    0x05,0x01,0x09,0x30,0x09,0x31,0x16,0x01,0x80,0x26,0xff,0x7f,
    0x75,0x10,0x95,0x02,0x81,0x06, // signed relative X/Y
    0x09,0x38,0x15,0x81,0x25,0x7f,0x75,0x08,0x95,0x01,0x81,0x06, // Wheel
    0x05,0x0c,0x0a,0x38,0x02,0x81,0x06, // Consumer AC Pan 0238
    0xc0,0xc0
};
static inline void b5q_mouse_report(uint8_t out[8],unsigned buttons,int dx,int dy,int wheel,int pan) {
    const unsigned x=uint16_t(dx),y=uint16_t(dy);
    out[0]=0x1a;out[1]=buttons&3;out[2]=uint8_t(x);out[3]=uint8_t(x>>8);
    out[4]=uint8_t(y);out[5]=uint8_t(y>>8);out[6]=uint8_t(wheel);out[7]=uint8_t(pan);
}
